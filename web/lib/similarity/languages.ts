import type { Language } from "@/drizzle/schemas/submissions";

// Lexer settings per submission language. The tokenizer (./tokenize.ts) is a
// single scanner driven by these, so adding a language means adding a row
// here, not another lexer.
export type LexerConfig = {
  lineComments: string[];
  blockComments: { open: string; close: string; nested?: boolean }[];
  /** Quote characters that open a string (or char) literal. */
  quotes: string[];
  /** Python `"""…"""` / `'''…'''`. */
  tripleQuotes?: boolean;
  /** Identifier prefixes that glue onto a following quote (`f"…"`, `b'…'`). */
  stringPrefixes?: string[];
  /** Rust `r"…"` / `r#"…"#` and `'a` lifetimes (a `'` is a char only when closed). */
  rust?: boolean;
  /** Lines starting with one of these (after indentation) are dropped until end of line. */
  skipLines?: string[];
  /** Statements starting with one of these words are dropped up to the next `;`. */
  skipStatements?: string[];
  keywords: Set<string>;
};

